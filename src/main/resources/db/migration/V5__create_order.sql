-- 다른 모듈의 테이블(visit, fee_item)에는 외래 키를 걸지 않는다.
-- 각 모듈의 테이블은 그 모듈의 마이그레이션이 소유하고, 가리키는 행은 지워지지 않으므로(접수 취소 보류, A-28)
-- 없는 id로 저장하는 것만 막으면 된다. 이는 오더 발행 때 공개 조회(reception, master)로 확인한다.

create table medical_order(
  id number(19) generated by default as identity primary key,
  visit_id number(19) not null,
  doctor_no varchar2(20) not null,
  ordered_at timestamp not null
);
create index idx_medical_order_visit on medical_order (visit_id);

create table order_item(
  id number(19) generated by default as identity primary key,
  order_id number(19) not null,
  fee_item_id number(19) not null,
  quantity number(5) not null,
  status varchar2(20) not null,
  executable_before_payment number(1) not null,
  pre_execution_basis varchar2(20),
  constraint fk_order_item_order foreign key (order_id) references medical_order (id),
  constraint ck_order_item_quantity check (quantity >= 1),
  constraint ck_order_item_status check (status in ('ORDERED', 'EXECUTED', 'CANCEL_REQUESTED', 'CANCELLED', 'EXPIRED')),
  constraint ck_order_item_pre_exec check (executable_before_payment in (0, 1)),
  -- is not null을 따로 적는다. 체크 제약은 결과가 UNKNOWN이면 통과시키는데,
  -- null in (...)은 false가 아니라 UNKNOWN이라서 이것만으로는 "승인인데 근거 없음"을 막지 못한다.
  constraint ck_order_item_pre_exec_basis check (
    (executable_before_payment = 1 and pre_execution_basis is not null and pre_execution_basis in ('DOCTOR', 'FEE_ITEM_DEFAULT'))
    or (executable_before_payment = 0 and pre_execution_basis is null)
  )
);
create index idx_order_item_order on order_item (order_id);

create table order_item_cancellation(
  id number(19) generated by default as identity primary key,
  order_item_id number(19) not null,
  doctor_no varchar2(20) not null,
  reason varchar2(200) not null,
  cancelled_at timestamp not null,
  constraint fk_order_cancel_item foreign key (order_item_id) references order_item (id),
  constraint uk_order_cancel_item unique (order_item_id)
);

