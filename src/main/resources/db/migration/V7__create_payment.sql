-- 다른 모듈의 테이블(invoice, visit, order_item, counter)에는 외래 키를 걸지 않는다(V5, V6과 같은 이유).
-- 슬라이스 1은 현금 수납의 정상 흐름만 담는다(payment.md 7절).
--
-- [이중 수납 방어는 일부러 걸지 않는다]
-- payment.invoice_id의 유일 제약(INV-05: 한 산정에 수납 건 하나)과
-- "오더 항목은 완료된 수납 건 하나에만"(INV-03)을 막는 제약이 없다. 빠뜨린 것이 아니다.
-- 이 흐름 위에서 C-03, C-06을 재현 테스트로 먼저 실패시킨 뒤, ADR-0003에서 방법을 실험으로 골라 넣는다.

create table payment(
  id number(19) generated by default as identity primary key,
  invoice_id number(19) not null,
  visit_id number(19) not null,
  counter_id number(19) not null,
  cashier_no varchar2(20) not null,
  patient_amount number(19) not null,
  status varchar2(20) not null,
  started_at timestamp not null,
  completed_at timestamp,
  constraint ck_payment_amount check (patient_amount >= 0),
  constraint ck_payment_status check (status in ('IN_PROGRESS', 'COMPLETED', 'REJECTED', 'HELD')),
  -- 완료된 수납 건만 완료 시각을 갖는다. is not null을 따로 적는 이유는 V5의 주석과 같다
  -- (체크 제약은 결과가 UNKNOWN이면 통과시킨다).
  constraint ck_payment_completed_at check (
    (status = 'COMPLETED' and completed_at is not null)
    or (status <> 'COMPLETED' and completed_at is null)
  )
);
create index idx_payment_visit on payment (visit_id);
-- 유일 제약이 아니라 조회용 인덱스다. INV-05는 ADR-0003에서 정한다.
create index idx_payment_invoice on payment (invoice_id);

create table payment_item(
  id number(19) generated by default as identity primary key,
  payment_id number(19) not null,
  order_item_id number(19) not null,
  constraint fk_payment_item_payment foreign key (payment_id) references payment (id),
  -- 한 수납 건 안에서만 유일하다. 거부·보류된 수납 건이 있으면 같은 항목이 새 수납 건에 다시 들어가므로,
  -- INV-03은 order_item_id 단독 유일 제약으로 표현할 수 없다. ADR-0003에서 정한다.
  constraint uk_payment_item unique (payment_id, order_item_id)
);
-- "수납하지 않은 항목"(A-02)을 고를 때, 항목이 완료된 수납 건에 들어 있는지 찾는 데 쓴다.
create index idx_payment_item_order_item on payment_item (order_item_id);

create table payment_line(
  id number(19) generated by default as identity primary key,
  payment_id number(19) not null,
  method varchar2(10) not null,
  status varchar2(20) not null,
  received_amount number(19) not null,
  applied_amount number(19) not null,
  received_at timestamp not null,
  constraint fk_payment_line_payment foreign key (payment_id) references payment (id),
  -- 슬라이스 1은 현금만 다룬다. 카드 수단과 카드 결제 상태는 카드 슬라이스에서 이 제약을 넓혀 추가한다.
  constraint ck_payment_line_method check (method in ('CASH')),
  constraint ck_payment_line_status check (status in ('RECEIVED', 'RETURNED')),
  constraint ck_payment_line_applied check (applied_amount > 0),
  -- 거스름돈(받은 금액 − 수납 반영 금액)은 저장하지 않는다. 대신 음수가 될 수 없게 한다.
  constraint ck_payment_line_received check (received_amount >= applied_amount)
);
create index idx_payment_line_payment on payment_line (payment_id);

