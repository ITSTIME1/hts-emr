create table visit(
  id number(19) generated by default as identity primary key,
  patient_no varchar2(20) not null,
  department_code varchar2(10) not null,
  doctor_no varchar2(20) not null,
  visit_date date not null,
  registered_at timestamp not null,
  constraint uk_visit_patient_date_dept unique (patient_no, visit_date, department_code),
  constraint ck_visit_date_only check (visit_date = trunc(visit_date))
);

create table eligibility(

  id number(19) generated by default as identity primary key,
  visit_id number(19) not null,
  seq number(5) not null,
  insurance_type varchar2(20) not null,
  copay_rate number(3) not null,
  recorded_at timestamp not null,
  constraint fk_eligibility_visit foreign key (visit_id) references visit (id),
  constraint uk_eligibility_visit_seq unique (visit_id, seq),
  constraint ck_eligibility_seq check (seq >= 1),
  constraint ck_eligibility_type check (insurance_type in ('NATIONAL_HEALTH', 'UNINSURED')),
  constraint ck_eligibility_rate check (copay_rate between 0 and 100),
  constraint ck_eligibility_uninsured_rate check (insurance_type <> 'UNINSURED' or copay_rate = 100)
);

