CREATE TABLE fee_item (
    id                         NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                       VARCHAR2(20)  NOT NULL,
    name                       VARCHAR2(100) NOT NULL,
    coverage_type              VARCHAR2(20)  NOT NULL,
    executable_before_payment  NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT uk_fee_item_code UNIQUE (code),
    CONSTRAINT ck_fee_item_coverage CHECK (coverage_type IN ('COVERED', 'NON_COVERED')),
    CONSTRAINT ck_fee_item_pre_exec CHECK (executable_before_payment IN (0, 1))
);

CREATE TABLE fee_price (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fee_item_id     NUMBER(19) NOT NULL,
    effective_from  DATE       NOT NULL,
    amount          NUMBER(19) NOT NULL,
    CONSTRAINT fk_fee_price_item FOREIGN KEY (fee_item_id) REFERENCES fee_item (id),
    CONSTRAINT uk_fee_price_item_date UNIQUE (fee_item_id, effective_from),
    CONSTRAINT ck_fee_price_amount CHECK (amount >= 0)
);

CREATE TABLE counter (
    id    NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code  VARCHAR2(20)  NOT NULL,
    name  VARCHAR2(100) NOT NULL,
    CONSTRAINT uk_counter_code UNIQUE (code)
);

COMMENT ON TABLE fee_item IS '수가 항목(FeeItem). 진찰·검사·처치처럼 진료비를 받을 수 있는 행위의 종류. 삭제하지 않고 사용 종료일로 막는다(A-28)';
COMMENT ON COLUMN fee_item.code IS '수가 코드. 사람이 쓰는 식별자';
COMMENT ON COLUMN fee_item.coverage_type IS '급여 구분. COVERED(급여), NON_COVERED(비급여)';
COMMENT ON COLUMN fee_item.executable_before_payment IS '선시행 기본값. 1이면 의사 승인 없이 선시행 대상(A-08)';

COMMENT ON TABLE fee_price IS '수가(FeePrice). 수가 항목의 단가. 진료일에 유효한 것을 적용하고(A-06), 적용을 시작한 단가는 고치지 않는다(A-28)';
COMMENT ON COLUMN fee_price.effective_from IS '적용 시작일. 시각 없이 날짜만 넣는다';
COMMENT ON COLUMN fee_price.amount IS '단가. 원 단위 정수';

COMMENT ON TABLE counter IS '창구(Counter). 수납과 환불을 처리하고 따로 마감하는 단위';
