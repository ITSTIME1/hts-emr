create table invoice(
  id number(19) generated by default as identity primary key,
  visit_id number(19) not null,
  eligibility_seq number(5) not null,
  insurance_type varchar2(20) not null,
  copay_rate number(3) not null,
  covered_line_sum number(19) not null,
  covered_total number(19) not null,
  covered_copay number(19) not null,
  insurer_amount number(19) not null,
  non_covered_total number(19) not null,
  patient_amount number(19) not null,
  calculated_at timestamp not null,
  constraint ck_invoice_eligibility_seq check (eligibility_seq >= 1),
  constraint ck_invoice_type check (insurance_type in ('NATIONAL_HEALTH', 'UNINSURED')),
  constraint ck_invoice_rate check (copay_rate between 0 and 100),
  constraint ck_invoice_uninsured_rate check (insurance_type <> 'UNINSURED' or copay_rate = 100),
  constraint ck_invoice_amounts check (covered_copay >= 0 and insurer_amount >= 0 and non_covered_total >= 0),
  constraint ck_invoice_covered_total check (covered_total between 0 and covered_line_sum),
  constraint ck_invoice_insurer check (insurer_amount = covered_total - covered_copay),
  constraint ck_invoice_patient check (patient_amount = covered_copay + non_covered_total),
  constraint ck_invoice_uninsured check (
    insurance_type <> 'UNINSURED' or (covered_total = covered_line_sum and insurer_amount = 0)
  )
);
create index idx_invoice_visit on invoice (visit_id);

create table invoice_line(
  id number(19) generated by default as identity primary key,
  invoice_id number(19) not null,
  order_item_id number(19) not null,
  fee_item_id number(19) not null,
  coverage_type varchar2(20) not null,
  unit_price number(19) not null,
  quantity number(5) not null,
  line_total number(19) not null,
  constraint fk_invoice_line_invoice foreign key (invoice_id) references invoice (id),
  constraint uk_invoice_line_item unique (invoice_id, order_item_id),
  constraint ck_invoice_line_coverage check (coverage_type in ('COVERED', 'NON_COVERED')),
  constraint ck_invoice_line_price check (unit_price >= 0),
  constraint ck_invoice_line_quantity check (quantity >= 1),
  constraint ck_invoice_line_total check (line_total = unit_price * quantity)
);
create index idx_invoice_line_invoice on invoice_line (invoice_id);

